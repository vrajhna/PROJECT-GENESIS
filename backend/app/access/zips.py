"""ZIP project access: safe extract in, reproducible archive out."""

from __future__ import annotations

import io
import zipfile
from pathlib import Path


def safe_extract(data: bytes, dest: Path, limit_files: int = 2000,
                 limit_bytes: int = 200 * 1024 * 1024) -> list[str]:
    """Extract a ZIP, rejecting zip-slip paths, absolute paths and bombs.

    Returns the list of extracted relative paths. Never writes outside dest.
    """
    dest = dest.resolve()
    dest.mkdir(parents=True, exist_ok=True)
    names: list[str] = []
    total = 0
    with zipfile.ZipFile(io.BytesIO(data)) as zf:
        members = zf.infolist()
        if len(members) > limit_files:
            raise ValueError(f"too many files: {len(members)}")
        for member in members:
            total += member.file_size
            if total > limit_bytes:
                raise ValueError("archive too large")
            target = (dest / member.filename).resolve()
            if target != dest and dest not in target.parents:
                raise ValueError(f"blocked path escape: {member.filename}")
            if member.is_dir():
                target.mkdir(parents=True, exist_ok=True)
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            with zf.open(member) as src, open(target, "wb") as out:
                out.write(src.read())
            names.append(str(target.relative_to(dest)))
    return names


def make_zip(source: Path, extra: dict[str, str] | None = None) -> bytes:
    """Archive a project dir (excluding venvs, caches, git) + SETUP notes."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(source.rglob("*")):
            if not path.is_file():
                continue
            if any(part in (".venv", "__pycache__", ".git", ".pytest_cache", ".genesis")
                   for part in path.parts):
                continue
            zf.write(path, path.relative_to(source))
        zf.writestr("SETUP.md", (extra or {}).get("setup", SETUP_TEMPLATE))
    return buf.getvalue()


SETUP_TEMPLATE = """# Setup (generated by Genesis)

Requires Python 3.10+.

```sh
python3 -m venv .venv
.venv/bin/pip install pytest
python3 app_server.py --port 8000   # preview at http://127.0.0.1:8000
.venv/bin/python -m pytest -q       # run tests
```
"""


def inspect_tree(source: Path, limit: int = 200) -> list[str]:
    return sorted(
        str(p.relative_to(source)) for p in source.rglob("*")
        if p.is_file() and ".git" not in p.parts
        and "__pycache__" not in p.parts and ".venv" not in p.parts)[:limit]
