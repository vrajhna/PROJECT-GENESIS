"""Specialized engineering agents: logical roles, not free agents.

Each role has a typed contract (inputs → structured outputs) and runs
through the real engines: spec parser, workspace builder, pytest, and the
approval gate. The orchestrator (run.py) sequences them; no role shells out
on its own except TestingAgent's pytest invocation.
"""

from __future__ import annotations

import os
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from ..builder.approvals import ApprovalGate
from ..builder.files import GenesisWorkspace
from ..spec.engine import parse_specification, to_artifacts

SECRET_PATTERNS = [
    re.compile(r"(?i)\b(api[_-]?key|secret|passwd|password)\b\s*[:=]\s*['\"][^'\"]{4,}['\"]"),
    re.compile(r"sk-(live|test)-[A-Za-z0-9]{8,}"),
    re.compile(r"ghp_[A-Za-z0-9]{8,}"),
    re.compile(r"LLM_[A-Za-z0-9_-]{8,}"),
]


@dataclass
class AgentResult:
    ok: bool
    agent: str
    summary: str
    data: dict = field(default_factory=dict)
    evidence: list[str] = field(default_factory=list)


class ArchitectAgent:
    """Requirement interpretation, architecture, planning."""

    name = "architect"

    def run(self, spec: str) -> AgentResult:
        reqs = parse_specification(spec)
        if not reqs:
            return AgentResult(ok=False, agent=self.name,
                               summary="Empty specification — clarification required.",
                               data={"needs_clarification": True})
        return AgentResult(
            ok=True, agent=self.name,
            summary=f"{len(reqs)} requirements extracted.",
            data=to_artifacts(reqs),
            evidence=[f"{r.id} [{r.priority}] {r.description[:60]}" for r in reqs],
        )


class BuilderAgent:
    """File management + implementation behind the workspace guard."""

    name = "builder"

    def __init__(self, workspace: GenesisWorkspace) -> None:
        self.workspace = workspace

    def scaffold(self, requirements: list[dict]) -> AgentResult:
        """Template-based codegen: a runnable module + test derived from the spec.

        Deterministic today (model-driven generation arrives with Wonder
        integration); every file it writes is exercised by real tests below.
        """
        first = requirements[0]["description"] if requirements else "unspecified"
        count = len(requirements)
        solution = (
            f'"""Generated by Genesis BuilderAgent (template v1) from {count} requirement(s)."""\n'
            f"\nFIRST_REQUIREMENT = {first!r}\n"
            f"REQUIREMENT_COUNT = {count}\n"
            "\n"
            "def describe() -> str:\n"
            '    """One-line summary of what was specified."""\n'
            "    return f\"{REQUIREMENT_COUNT} requirement(s); first: {FIRST_REQUIREMENT}\"\n"
        )
        test = (
            "# Generated by Genesis BuilderAgent (template v1).\n"
            "from solution import FIRST_REQUIREMENT, REQUIREMENT_COUNT, describe\n"
            "\n"
            "def test_requirements_present():\n"
            "    assert REQUIREMENT_COUNT > 0\n"
            "    assert isinstance(FIRST_REQUIREMENT, str) and FIRST_REQUIREMENT.strip()\n"
            "\n"
            "def test_describe_mentions_first():\n"
            "    assert FIRST_REQUIREMENT[:20] in describe()\n"
        )
        self.workspace.create_file("solution.py", solution, overwrite=True)
        self.workspace.create_file("test_solution.py", test, overwrite=True)
        self.workspace.create_file("SPEC.json", __import__("json").dumps(
            {"requirements": requirements}, indent=2), overwrite=True)
        return AgentResult(
            ok=True, agent=self.name,
            summary=f"Scaffolded solution.py + test_solution.py from {count} requirement(s).",
            data={"files": ["solution.py", "test_solution.py", "SPEC.json"]},
            evidence=[f"audit entries: {len(self.workspace.audit)}"],
        )


class TestingAgent:
    """Test generation (pending), execution, interpretation, coverage, regression.

    Execution is always deterministic pytest. Interpretation parses real
    output: failed test names, coverage when pytest-cov is installed,
    regression by diffing against the previous run in the same repo.
    """

    name = "testing"

    def run(self, repo: Path, timeout_s: int = 120) -> AgentResult:
        try:
            proc = subprocess.run(
                ["python3", "-m", "pytest", "-q", "-rf"], cwd=str(repo),
                capture_output=True, text=True, timeout=timeout_s, shell=False)
        except subprocess.TimeoutExpired:
            return AgentResult(ok=False, agent=self.name, summary="pytest timed out.")
        except FileNotFoundError:
            return AgentResult(ok=False, agent=self.name, summary="pytest not installed.")
        out = (proc.stdout + proc.stderr)[-4000:]
        match = re.search(r"(\d+) passed(?:, (\d+) (?:skipped|failed|error))?", out)
        passed = int(match.group(1)) if match else 0
        extra = int(match.group(2)) if match and match.group(2) else 0
        failed_tests = sorted(set(re.findall(r"^FAILED (\S+)", out, re.M)))
        coverage = self._coverage(repo, timeout_s)
        regression = self._regression(repo, set(failed_tests))
        interpretation = (
            f"{passed} passed" + (f", {extra} other" if extra else "") + ". "
            + (f"Failing: {', '.join(failed_tests)}. " if failed_tests else "No failures. ")
            + coverage + " " + regression)
        failed = proc.returncode != 0
        return AgentResult(
            ok=not failed, agent=self.name,
            summary=f"pytest exit {proc.returncode}: {passed} passed"
                    + (f", {extra} other" if extra else "") + ".",
            data={"exit_code": proc.returncode, "passed": passed,
                  "failed_or_other": extra, "failed_tests": failed_tests,
                  "interpretation": interpretation.strip()},
            evidence=[out.strip().splitlines()[-1] if out.strip() else "(no output)"],
        )

    def _coverage(self, repo: Path, timeout_s: int) -> str:
        import importlib.util
        if importlib.util.find_spec("pytest_cov") is None:
            return "Coverage: pytest-cov not installed (pending)."
        try:
            proc = subprocess.run(
                ["python3", "-m", "pytest", "-q", "--cov=.", "--cov-report=term-missing"],
                cwd=str(repo), capture_output=True, text=True,
                timeout=timeout_s, shell=False)
            total = re.search(r"TOTAL\s+\d+\s+\d+\s+(\d+%)", proc.stdout)
            return f"Coverage: {total.group(1)}." if total else "Coverage: ran, unparsed."
        except Exception:
            return "Coverage: error running pytest-cov."

    def _regression(self, repo: Path, failed: set[str]) -> str:
        marker = repo / ".genesis" / "last_failures.txt"
        first = not marker.exists()
        prev = set(marker.read_text().split()) if not first else set()
        marker.parent.mkdir(parents=True, exist_ok=True)
        marker.write_text("\n".join(sorted(failed)))
        if first:
            return "Regression: baseline recorded."
        new = failed - prev
        fixed = prev - failed
        parts = []
        if new:
            parts.append(f"new failures: {', '.join(sorted(new))}")
        if fixed:
            parts.append(f"fixed: {', '.join(sorted(fixed))}")
        return "Regression: " + ("; ".join(parts) + "." if parts else "no change.")


class ReviewerAgent:
    """Independent review: secrets scan + no-untested-passed enforcement."""

    name = "reviewer"

    def run(self, repo: Path) -> AgentResult:
        findings: list[str] = []
        for path in sorted(repo.rglob("*.py")):
            if ".venv" in path.parts or "__pycache__" in path.parts:
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            for pattern in SECRET_PATTERNS:
                if pattern.search(text):
                    findings.append(f"possible secret in {path.name}")
                    break
        skip = {".venv", "__pycache__", ".git", ".genesis", ".pytest_cache",
                "node_modules"}
        has_tests = False
        for root, dirs, files in os.walk(repo):
            dirs[:] = [d for d in dirs if d not in skip]
            for f in files:
                if (f.startswith("test_") or f.endswith("_test.py")) and f.endswith(".py"):
                    has_tests = True
                    break
            if has_tests:
                break
        if not has_tests:
            findings.append("no tests present — nothing may be marked passed")
        ok = not findings
        return AgentResult(
            ok=ok, agent=self.name,
            summary="Review clean." if ok else f"{len(findings)} finding(s).",
            data={"findings": findings},
            evidence=[f"scanned {len(list(repo.rglob('*.py')))} python file(s)"],
        )


class MemoryEngine:
    """Project knowledge: successes, failures, verified lessons. File-backed.

    JSONL in the workspace `.genesis/` dir today; Postgres in Phase 6.
    Every lesson carries its evidence — no unverified lore.
    """

    name = "memory"

    def __init__(self, workspace: GenesisWorkspace) -> None:
        self.workspace = workspace
        self.path = workspace.root / ".genesis" / "memory.jsonl"

    def record(self, kind: str, lesson: str, evidence: str = "") -> dict:
        import json
        from datetime import datetime, timezone
        if kind not in ("success", "failure", "lesson"):
            raise ValueError(f"unknown memory kind: {kind}")
        entry = {"time": datetime.now(timezone.utc).isoformat(),
                 "kind": kind, "lesson": lesson, "evidence": evidence}
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with open(self.path, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry) + "\n")
        return entry

    def retrieve(self, keyword: str, limit: int = 5) -> list[dict]:
        import json
        if not self.path.exists():
            return []
        hits = []
        for line in self.path.read_text(encoding="utf-8").splitlines():
            try:
                entry = json.loads(line)
            except ValueError:
                continue
            if keyword.lower() in (entry.get("lesson", "") + entry.get("evidence", "")).lower():
                hits.append(entry)
        return hits[-limit:]


class DebuggerAgent:
    """Root-cause investigation: evidence in, structured diagnosis out."""

    name = "debugger"

    def run(self, failure: dict) -> AgentResult:
        fid = failure.get("id", "F-001")
        logs = failure.get("logs", "")
        hint = "see logs"
        last_line = [ln for ln in logs.strip().splitlines() if ln.strip()]
        if last_line:
            hint = last_line[-1][:160]
        diagnosis = {
            "failure_id": fid,
            "failure_category": failure.get("category", "unknown"),
            "suspected_root_cause": hint,
            "supporting_evidence": [hint] if hint != "see logs" else [],
            "alternative_explanations": ["environment issue", "stale checkpoint"],
            "affected_files": failure.get("files", []),
            "confidence_estimate": "low — execution evidence required",
            "proposed_repair": "reproduce under the sandbox, then minimal patch",
            "tests_required": ["failing test re-run", "regression suite"],
        }
        return AgentResult(ok=True, agent=self.name,
                           summary=f"Diagnosis {fid} drafted from evidence.",
                           data=diagnosis,
                           evidence=[hint])
