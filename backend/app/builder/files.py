"""Approval-gated workspace file operations. Stdlib only.

All writes stay inside the workspace root. Every mutation is audit-logged
in memory (persistent store is a Phase-6 item). Consequential restores go
through the approval gate in `approvals.py`.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path


@dataclass
class AuditEntry:
    time: str
    operation: str
    path: str
    detail: str = ""


@dataclass
class GenesisWorkspace:
    root: Path
    audit: list[AuditEntry] = field(default_factory=list)

    def _resolve(self, relpath: str) -> Path:
        candidate = (self.root / relpath).resolve()
        root = self.root.resolve()
        if candidate != root and root not in candidate.parents:
            raise ValueError(f"path escapes workspace: {relpath!r}")
        return candidate

    def _log(self, operation: str, path: str, detail: str = "") -> None:
        self.audit.append(
            AuditEntry(
                time=datetime.now(timezone.utc).isoformat(),
                operation=operation,
                path=path,
                detail=detail,
            )
        )

    def create_file(self, relpath: str, content: str, overwrite: bool = False) -> Path:
        target = self._resolve(relpath)
        if target.exists() and not overwrite:
            raise FileExistsError(f"file exists (overwrite=False): {relpath!r}")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        self._log("create_file", relpath, f"{len(content)} chars overwrite={overwrite}")
        return target

    def read_file(self, relpath: str) -> str:
        target = self._resolve(relpath)
        text = target.read_text(encoding="utf-8")
        self._log("read_file", relpath, f"{len(text)} chars")
        return text


GENESIS_MARKER = "Generated by Genesis"


def clear_generated_files(workdir: Path, filenames: list[str]) -> list[str]:
    """Remove prior template outputs — ONLY files carrying the Genesis marker.

    User content never matches, so user work is never touched. Returns removed paths.
    """
    removed = []
    for name in filenames:
        target = workdir / name
        try:
            if target.is_file() and GENESIS_MARKER in target.read_text(
                    encoding="utf-8", errors="ignore"):
                target.unlink()
                removed.append(name)
        except OSError:
            continue
    return removed
