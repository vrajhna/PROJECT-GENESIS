"""Approval-gated workspace file operations. Stdlib only.

All writes stay inside the workspace root. Every mutation is audit-logged
in memory (persistent store is a Phase-6 item). Consequential restores go
through the approval gate in `approvals.py`.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path


@dataclass
class AuditEntry:
    time: str
    operation: str
    path: str
    detail: str = ""


@dataclass
class GenesisWorkspace:
    root: Path
    audit: list[AuditEntry] = field(default_factory=list)

    def _resolve(self, relpath: str) -> Path:
        candidate = (self.root / relpath).resolve()
        root = self.root.resolve()
        if candidate != root and root not in candidate.parents:
            raise ValueError(f"path escapes workspace: {relpath!r}")
        return candidate

    def _log(self, operation: str, path: str, detail: str = "") -> None:
        self.audit.append(
            AuditEntry(
                time=datetime.now(timezone.utc).isoformat(),
                operation=operation,
                path=path,
                detail=detail,
            )
        )

    def create_file(self, relpath: str, content: str, overwrite: bool = False) -> Path:
        target = self._resolve(relpath)
        if target.exists() and not overwrite:
            raise FileExistsError(f"file exists (overwrite=False): {relpath!r}")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        self._log("create_file", relpath, f"{len(content)} chars overwrite={overwrite}")
        return target

    def read_file(self, relpath: str) -> str:
        target = self._resolve(relpath)
        text = target.read_text(encoding="utf-8")
        self._log("read_file", relpath, f"{len(text)} chars")
        return text


GENESIS_MARKER = "Generated by Genesis"


SNAPSHOT_SKIP_DIRS = frozenset({
    ".venv", "__pycache__", ".git", ".genesis", "node_modules",
    ".pytest_cache", ".mypy_cache", ".tox", "dist", "build",
})
SNAPSHOT_SKIP_SUFFIX = (".pyc", ".pyo", ".db", ".sqlite", ".log")
SNAPSHOT_MAX_FILES = 2000
SNAPSHOT_MAX_BYTES = 50 * 1024 * 1024
CONTEXT_PER_FILE = 4000
CONTEXT_MAX_BYTES = 32 * 1024
TEXT_SUFFIX = frozenset({
    ".py", ".js", ".ts", ".tsx", ".jsx", ".html", ".css", ".json",
    ".md", ".txt", ".yml", ".yaml", ".toml", ".ini", ".cfg", ".sql",
    ".sh", ".env.example", ".gitignore",
})


def _snapshottable(root: Path, p: Path) -> bool:
    try:
        rel = p.relative_to(root)
    except ValueError:
        return False
    if any(part in SNAPSHOT_SKIP_DIRS for part in rel.parts):
        return False
    if p.is_dir():
        return True
    if p.suffix in SNAPSHOT_SKIP_SUFFIX:
        return False
    return True


def snapshot_project(workdir: Path) -> dict:
    """Copy user files to work/.genesis/snapshots/<ts>/ BEFORE generate runs.

    Best-effort and capped; never raises. Returns {at, files, bytes} or
    {skipped: reason}. Old snapshots pruned to the newest 5.
    """
    try:
        ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S")
        dest = workdir / ".genesis" / "snapshots" / ts
        files = 0
        total = 0
        for p in sorted(workdir.rglob("*")):
            if files >= SNAPSHOT_MAX_FILES or total >= SNAPSHOT_MAX_BYTES:
                break
            if not _snapshottable(workdir, p) or not p.is_file():
                continue
            try:
                size = p.stat().st_size
            except OSError:
                continue
            if total + size > SNAPSHOT_MAX_BYTES:
                break
            rel = p.relative_to(workdir)
            target = dest / rel
            try:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(p.read_bytes())
            except OSError:
                continue
            files += 1
            total += size
        if not files:
            return {"skipped": "nothing to snapshot"}
        try:
            snaps = sorted((workdir / ".genesis" / "snapshots").iterdir())
            for old in snaps[:-5]:
                import shutil
                shutil.rmtree(old, ignore_errors=True)
        except OSError:
            pass
        return {"at": ts, "files": files, "bytes": total}
    except Exception as e:
        return {"skipped": f"{type(e).__name__}"}


def _looks_text(p: Path) -> bool:
    if p.suffix in TEXT_SUFFIX or p.name in ("Dockerfile", "Makefile"):
        return True
    if not p.suffix or len(p.suffix) > 5:
        try:
            with open(p, "rb") as f:
                chunk = f.read(800)
            return b"\x00" not in chunk
        except OSError:
            return False
    return False


def collect_existing_context(workdir: Path) -> str:
    """Existing user code as model context (bounded). Empty when fresh."""
    try:
        parts: list[str] = []
        total = 0
        for p in sorted(workdir.rglob("*")):
            if total >= CONTEXT_MAX_BYTES:
                break
            if not _snapshottable(workdir, p) or not p.is_file():
                continue
            if not _looks_text(p):
                continue
            try:
                text = p.read_text(encoding="utf-8", errors="strict")[:CONTEXT_PER_FILE]
            except (OSError, ValueError):
                continue
            block = f"--- {p.relative_to(workdir)} ---\n{text}"
            if total + len(block.encode()) > CONTEXT_MAX_BYTES:
                break
            parts.append(block)
            total += len(block.encode())
        return "\n\n".join(parts)
    except Exception:
        return ""


def clear_generated_files(workdir: Path, filenames: list[str]) -> list[str]:
    """Remove prior template outputs — ONLY files carrying the Genesis marker.

    User content never matches, so user work is never touched. Returns removed paths.
    """
    removed = []
    for name in filenames:
        target = workdir / name
        try:
            if target.is_file() and GENESIS_MARKER in target.read_text(
                    encoding="utf-8", errors="ignore"):
                target.unlink()
                removed.append(name)
        except OSError:
            continue
    return removed
