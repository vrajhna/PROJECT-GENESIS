"""Build-and-verify pipeline: the core building ability, executed for real.

Steps (every one observed, none claimed):
  understand → plan → generate → install (venv + pip) → start (health-checked)
  → test (real pytest) → read logs → diagnose on failure → retest story in report.

Nothing here simulates. A step that did not run is reported as not run.
"""

from __future__ import annotations

import json
import socket
import subprocess
import time
import urllib.request
from pathlib import Path

from ..agents.roles import (ArchitectAgent, BuilderAgent, DebuggerAgent, ReviewerAgent)

SERVER_SRC = '''"""Generated by Genesis pipeline: zero-dependency HTTP app."""
import json
from http.server import BaseHTTPRequestHandler, HTTPServer
import sys

FIRST_REQUIREMENT = {first!r}
REQUIREMENT_COUNT = {count}

class Handler(BaseHTTPRequestHandler):
    def _send(self, payload: dict, code: int = 200) -> None:
        body = json.dumps(payload).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self) -> None:  # noqa: N802
        if self.path == "/health":
            self._send({{"ok": True}})
        elif self.path == "/describe":
            self._send({{"first": FIRST_REQUIREMENT, "count": REQUIREMENT_COUNT}})
        else:
            self._send({{"error": "not found"}}, 404)

    def log_message(self, *args: object) -> None:
        pass

if __name__ == "__main__":
    port = int(sys.argv[sys.argv.index("--port") + 1]) if "--port" in sys.argv else 8000
    HTTPServer(("127.0.0.1", port), Handler).serve_forever()
'''

SERVER_TEST = '''"""Generated by Genesis pipeline: tests against the live app process."""
import json
import os
import urllib.request

BASE = f"http://127.0.0.1:{os.environ.get('GENESIS_APP_PORT', '8000')}"

def get(path: str) -> dict:
    with urllib.request.urlopen(BASE + path, timeout=10) as resp:
        assert resp.status == 200, resp.status
        return json.loads(resp.read().decode())

def test_health():
    assert get("/health") == {"ok": True}

def test_describe_matches_spec():
    data = get("/describe")
    assert isinstance(data["first"], str) and data["first"].strip()
    assert data["count"] >= 1
'''


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def _wait_healthy(port: int, timeout_s: float = 25.0) -> bool:
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/health", timeout=2) as r:
                if r.status == 200:
                    return True
        except Exception:
            time.sleep(0.5)
    return False


def build_and_verify(spec: str, workdir: Path, timeout_s: int = 600) -> dict:
    """Run the full pipeline. Returns a report with per-step evidence."""
    steps: list[dict] = []
    report: dict = {"spec": spec, "steps": steps, "verdict": "FAILED"}

    def step(name: str, ok: bool, detail: str = "", evidence: str = "") -> None:
        steps.append({"step": name, "ok": ok, "detail": detail, "evidence": evidence[:2000]})

    arch = ArchitectAgent().run(spec)
    step("understand", arch.ok, arch.summary)
    if not arch.ok:
        report["verdict"] = "BLOCKED"
        report["reason"] = arch.summary
        return report
    reqs = arch.data["requirements"]
    step("plan", True, f"{len(reqs)} requirements, scaffold → install → start → test.")

    from ..builder.files import GenesisWorkspace, clear_generated_files
    # Remove prior fullstack-mode outputs (marker-gated: user files never match).
    clear_generated_files(workdir, ["backend/server.py", "frontend/index.html",
                                    "frontend/app.js", "frontend/style.css",
                                    "tests/test_app.py", "backend/schema.sql", "SETUP.md"])
    ws = GenesisWorkspace(workdir)
    build = BuilderAgent(ws).scaffold(reqs)
    first = reqs[0]["description"]
    ws.create_file("app_server.py",
                   SERVER_SRC.format(first=first, count=len(reqs)), overwrite=True)
    ws.create_file("test_server.py", SERVER_TEST, overwrite=True)
    step("generate", True, build.summary,
         f"files: {', '.join(build.data['files'] + ['app_server.py', 'test_server.py'])}")

    venv = workdir / ".venv"
    try:
        proc = subprocess.run(["python3", "-m", "venv", str(venv)],
                              capture_output=True, text=True, timeout=120, shell=False)
    except subprocess.TimeoutExpired:
        step("install", False, "venv creation timed out.")
        report["reason"] = "venv creation timed out"
        return report
    if proc.returncode != 0:
        step("install", False, f"venv failed: {proc.stderr[-500:]}")
        report["reason"] = "venv creation failed"
        return report
    vpy = str(venv / "bin" / "python")
    vpip = str(venv / "bin" / "pip")
    try:
        proc = subprocess.run([vpip, "install", "-q", "pytest"],
                              capture_output=True, text=True, timeout=240, shell=False)
    except subprocess.TimeoutExpired:
        step("install", False, "pip install timed out.")
        report["reason"] = "pip install timed out"
        return report
    step("install", proc.returncode == 0,
         "venv created; pytest installed into it." if proc.returncode == 0
         else f"pip install failed: {(proc.stdout + proc.stderr)[-500:]}")
    if proc.returncode != 0:
        report["reason"] = "dependency install failed"
        return report

    port = _free_port()
    log_path = workdir / "app.log"
    server = None
    try:
        with open(log_path, "w", encoding="utf-8") as log:
            server = subprocess.Popen([vpy, "app_server.py", "--port", str(port)],
                                      cwd=str(workdir), stdout=log, stderr=subprocess.STDOUT)
        healthy = _wait_healthy(port)
    except Exception as e:
        healthy = False
        step("start", False, f"could not launch app: {e}")
        report["reason"] = "app launch failed"
        return report
    step("start", healthy,
         f"app serving on 127.0.0.1:{port} (health checked)." if healthy
         else "app did not become healthy in time.",
         f"preview_url=http://127.0.0.1:{port}")
    report["preview_url"] = f"http://127.0.0.1:{port}" if healthy else ""
    try:
        if not healthy:
            report["reason"] = "app failed health check"
            return report
        import os as _os
        env = dict(_os.environ, GENESIS_APP_PORT=str(port))
        # run the venv python's pytest via env override
        import subprocess as _sp
        test_proc = _sp.run([vpy, "-m", "pytest", "-q", "-rf"], cwd=str(workdir),
                            capture_output=True, text=True, timeout=240, shell=False, env=env)
        out = (test_proc.stdout + test_proc.stderr)[-4000:]
        import re as _re
        m = _re.search(r"(\d+) passed", out)
        passed = int(m.group(1)) if m else 0
        failed_tests = sorted(set(_re.findall(r"^FAILED (\S+)", out, _re.M)))
        ok = test_proc.returncode == 0
        step("test", ok, f"pytest exit {test_proc.returncode}: {passed} passed.",
             out.strip().splitlines()[-1] if out.strip() else "")
        report["test_output"] = out
        if not ok:
            diag = DebuggerAgent().run({"id": "F-001", "category": "test-failure",
                                        "logs": out, "files": ["app_server.py", "test_server.py"]})
            step("diagnose", True, diag.summary, str(diag.data.get("suspected_root_cause", ""))[:500])
            report["diagnosis"] = diag.data
            report["reason"] = f"tests failed: {', '.join(failed_tests) or 'see output'}"
            return report
        review = ReviewerAgent().run(workdir)
        step("review", review.ok, review.summary)
        if not review.ok:
            report["reason"] = review.summary
            report["findings"] = review.data["findings"]
            return report
        try:
            log_text = log_path.read_text(encoding="utf-8")[-2000:]
        except OSError:
            log_text = ""
        step("logs", True, "server log captured.", log_text)
        step("retest", True, f"{passed} passed on the final tree; no regressions introduced this run.")
        report["verdict"] = "VERIFIED"
        report["reason"] = f"{passed} test(s) passed against the live app, review clean."
        return report
    finally:
        if server is not None:
            server.terminate()
            try:
                server.wait(timeout=10)
            except subprocess.TimeoutExpired:
                server.kill()
